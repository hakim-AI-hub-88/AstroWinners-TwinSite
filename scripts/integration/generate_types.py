"""Generate structural TS types from schemas; runtime validators enforce refinements."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[2]
NAMES = ['health','mission_request','mission_result','mission_accepted','mission_status','progress_event','events','evidence_observation','asset_manifest','release_evidence','error','alternatives_request','data_compare_request']


def title(value):
    return ''.join(part.capitalize() for part in value.split('_'))


def literal(value):
    if isinstance(value, list):
        return '[' + ', '.join(literal(v) for v in value) + ']'
    return json.dumps(value)


def convert(schema):
    if '$ref' in schema:
        return title(Path(schema['$ref']).name.removesuffix('.schema.json'))
    if 'const' in schema:
        return literal(schema['const'])
    if 'enum' in schema:
        return ' | '.join(literal(v) for v in schema['enum'])
    if 'oneOf' in schema:
        return ' | '.join('(' + convert(s) + ')' for s in schema['oneOf'])
    t = schema.get('type')
    if isinstance(t,list):
        return ' | '.join(convert({**schema,'type':v}) for v in t)
    if t == 'object':
        props = schema.get('properties',{})
        if not props:
            extra = schema.get('additionalProperties',True)
            return 'Record<string, ' + (convert(extra) if isinstance(extra,dict) else 'unknown') + '>'
        required = schema.get('required',[])
        return '{\n' + '\n'.join('  '+json.dumps(k)+('' if k in required else '?')+': '+convert(v)+';' for k,v in props.items())+'\n}'
    if t == 'array':
        return 'Array<' + convert(schema.get('items',{})) + '>'
    return {'string':'string','number':'number','integer':'number','boolean':'boolean','null':'null'}.get(t,'unknown')


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text = '// GENERATED by scripts/integration/generate_types.py. Do not edit.\n// JSON Schemas are authoritative for bounds, formats and cross-field rules.\n'
    for name in NAMES:
        text += '\nexport type ' + title(name) + ' = ' + convert(json.loads((ROOT/'contracts/v1'/(name+'.schema.json')).read_text())) + ';\n'
    path=ROOT/'contracts/types.ts'
    if args.check:
        if not path.exists() or path.read_text()!=text:
            raise SystemExit('Generated types are stale; run python scripts/integration/generate_types.py')
        print('PASS: generated TypeScript types match schemas')
    else:
        path.write_text(text)


if __name__ == '__main__':
    main()
